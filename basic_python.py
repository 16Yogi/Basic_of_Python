"""**Loop**
Loops in programming are used to repeat a block of code until the specified condition is met. A loop statement allows programmers to execute a statement or group of statements multiple times without repetition of code.

**1. For loop -** First initializes, then condition check then executes the body and at last, the update is done. This type of loop executes a code block multiple times and abbreviates the code that manages the loop variable.
**2. While loop -**first Initializes, then condition checks, and then executes the body, and updating can be inside the body. Repeats a statement or group of statements while a given condition is TRUE. it tests the condition before executing the loop body.
**3. do while loop -** do-while first ececutes the body and then the condition check is done. We can iterate a loop inside anothe loop.


**Entry COntrolled loops**

In entry controlled loop the test condition is checked before entering the main body of the loop. For Loop and While Loop is Entry-controlled loops.

**Exit Controlled loop**

In exit controlled loops the test condition is evaluated at the end of the loop body. The loop body will execute at least once, irrespective of whether the condition is true or false. do-while Loop is Exit Controlled loop.



**Name of the control statement -**

**1. Break statement -** This command terminates the loop's execution and transfers the program's control to the statement next to the loop.

**2. Continue statement -** This command skips the current iteration of the loop. The statements following the continue statement are not executed once the Python interpreter reaches the continue statement.

**3. Pass statement -** The pass statement is used when a statement is syntactically necessary, but no code is to be executed.
"""

